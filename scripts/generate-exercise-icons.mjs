import { readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const rootDirectory = path.resolve(scriptDirectory, '..')
const iconDirectory = path.join(rootDirectory, 'src/exercises/icons')
const manifestPath = path.join(iconDirectory, 'manifest.ts')
const generatedDirectory = path.join(iconDirectory, 'generated')

function fail(message) {
  throw new Error(`Exercise icon manifest: ${message}`)
}

function readLiteral(node) {
  if (ts.isStringLiteral(node)) return node.text
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(readLiteral)
  if (ts.isObjectLiteralExpression(node)) {
    return Object.fromEntries(
      node.properties.map((property) => {
        if (!ts.isPropertyAssignment(property)) {
          fail('entries may contain only property assignments')
        }
        const name = property.name.getText().replaceAll(/["']/g, '')
        return [name, readLiteral(property.initializer)]
      }),
    )
  }
  fail(`unsupported manifest value ${node.getText()}`)
}

function unwrapExpression(node) {
  if (ts.isSatisfiesExpression(node) || ts.isAsExpression(node)) {
    // Manifest expressions can contain nested `as const satisfies` wrappers.
    // eslint-disable-next-line unicorn/no-useless-recursion
    return unwrapExpression(node.expression)
  }
  return node
}

async function loadManifest() {
  const source = await readFile(manifestPath, 'utf8')
  const file = ts.createSourceFile(manifestPath, source, ts.ScriptTarget.Latest, true)
  let initializer
  for (const statement of file.statements) {
    if (!ts.isVariableStatement(statement)) continue
    const declaration = statement.declarationList.declarations.find(
      (candidate) => candidate.name.getText() === 'exerciseIconManifest',
    )
    if (declaration?.initializer) initializer = declaration.initializer
  }
  if (!initializer) fail('could not find exerciseIconManifest')
  const value = readLiteral(unwrapExpression(initializer))
  if (!Array.isArray(value)) fail('exerciseIconManifest must be an array')
  return value
}

function normalize(value) {
  return value.trim().toLocaleLowerCase('en-US').replaceAll(/[-_]+/g, ' ').replaceAll(/\s+/g, ' ')
}

async function validate(entries) {
  const keys = new Set()
  const aliases = new Map()
  for (const entry of entries) {
    for (const field of ['key', 'title', 'component', 'poseFamily']) {
      if (typeof entry[field] !== 'string' || entry[field].trim() === '')
        fail(`entry has invalid ${field}`)
    }
    for (const field of ['aliases', 'equipment', 'muscles']) {
      if (!Array.isArray(entry[field]) || entry[field].length === 0)
        fail(`${entry.key} has invalid ${field}`)
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(entry.key))
      fail(`${entry.key} is not a stable kebab-case key`)
    if (!/^[A-Z][A-Za-z0-9]*Icon$/.test(entry.component))
      fail(`${entry.key} references invalid component ${entry.component}`)
    if (keys.has(entry.key)) fail(`duplicate key ${entry.key}`)
    keys.add(entry.key)
    for (const alias of entry.aliases) {
      if (typeof alias !== 'string' || alias.trim() === '')
        fail(`${entry.key} has an invalid alias`)
      const normalized = normalize(alias)
      const owner = aliases.get(normalized)
      if (owner) fail(`duplicate alias ${alias} (${owner} and ${entry.key})`)
      aliases.set(normalized, entry.key)
    }
    try {
      const componentPath = path.join(iconDirectory, 'components', `${entry.component}.vue`)
      const componentStat = await stat(componentPath)
      if (!componentStat.isFile())
        fail(`${entry.key} component is not a file: ${entry.component}.vue`)
    } catch {
      fail(`${entry.key} references missing component components/${entry.component}.vue`)
    }
  }
}

function quote(value) {
  return JSON.stringify(value)
}

function generatedHeader() {
  return '// GENERATED by scripts/generate-exercise-icons.mjs. DO NOT EDIT.\n'
}

function createKeys(entries) {
  return `${generatedHeader()}\nexport const exerciseIconKeys = [\n${entries.map((entry) => `  ${quote(entry.key)},`).join('\n')}\n] as const\n\nexport type ExerciseIconKey = (typeof exerciseIconKeys)[number]\n`
}

function createAliases(entries) {
  const aliases = entries.flatMap((entry) =>
    entry.aliases.map((alias) => [normalize(alias), entry.key]),
  )
  aliases.sort(([left], [right]) => left.localeCompare(right))
  return `${generatedHeader()}\nimport type { ExerciseIconKey } from './iconKeys'\n\nexport const exerciseIconAliases: Readonly<Record<string, ExerciseIconKey>> = {\n${aliases.map(([alias, key]) => `  ${quote(alias)}: ${quote(key)},`).join('\n')}\n}\n`
}

function createRegistry(entries) {
  const imports = entries
    .map((entry) => `import ${entry.component} from '../components/${entry.component}.vue'`)
    .join('\n')
  const records = entries
    .map(
      (entry) =>
        `  ${quote(entry.key)}: { component: ${entry.component}, title: ${quote(entry.title)} },`,
    )
    .join('\n')
  return `${generatedHeader()}\nimport type { ExerciseIconComponent } from '../types'\nimport type { ExerciseIconKey } from './iconKeys'\n${imports}\n\nexport type ExerciseIconRegistryEntry = Readonly<{\n  component: ExerciseIconComponent\n  title: string\n}>\n\nexport const exerciseIconRegistry: Readonly<Record<ExerciseIconKey, ExerciseIconRegistryEntry>> = {\n${records}\n}\n`
}

const entries = await loadManifest()
await validate(entries)
await Promise.all([
  writeFile(path.join(generatedDirectory, 'iconKeys.ts'), createKeys(entries)),
  writeFile(path.join(generatedDirectory, 'iconAliases.ts'), createAliases(entries)),
  writeFile(path.join(generatedDirectory, 'iconRegistry.ts'), createRegistry(entries)),
])
console.info(`Generated exercise icon inventory for ${entries.length} icons.`)
